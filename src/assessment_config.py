'''
Configuration for private cybersecurity assessment storage.

Assessment records are stored separately from public
HTML reports generated by the Cpontrol Assurance Engine.
'''

from pathlib import Path
# Resolve the repository root relative to this module.
# This avoids depending on the terminal's working directory.
PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Defualt dorectory for private assessment JSON record.
ASSESSMENT_DIRECTORY = PROJECT_ROOT / 'data' / 'assessments'

def get_assessments_directory() -> Path:
    '''
    REturn the configured directory for private assessment records.

    Directory creation will be handled separately so that
    accessing configuration does not modify the filesystem.
    '''
    return ASSESSMENT_DIRECTORY
